"""Writes examples/runs.jsonl and examples/prices.json: SAMPLE DATA for the demo.

Nothing here is a measurement. The three models are made up ("small-a", "mid-b", "large-c"),
the prices are made up, and the token counts come from a seeded random generator shaped to
show a common pattern: the model with the cheapest tokens writes more of them, retries more,
and fails more. Each model logs usage in a different provider format on purpose, to show
that the tool normalizes OpenAI Chat, Anthropic Messages, and OpenAI Responses usage.
"""
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
rng = random.Random(7)
TASKS = ["fix-flaky-test", "add-pagination", "rename-config-key", "write-migration-note", "triage-issue-311",
         "bump-sdk-version", "add-retry-to-client", "summarize-pr-diff", "patch-null-check", "update-readme-usage"]

PRICES = {
    "_note": "SAMPLE prices for made-up models. USD per 1M tokens. Replace with your provider's current list prices.",
    "models": {
        "small-a": {"input": 0.10, "cached": 0.01, "output": 0.50},
        "mid-b": {"input": 1.00, "cached": 0.10, "cache_write": 1.25, "output": 5.00},
        "large-c": {"input": 3.00, "cached": 0.30, "output": 15.00},
    },
}


def j(base, spread=0.25):
    return int(base * (1 + rng.uniform(-spread, spread)))


rows = []
for t in TASKS:
    # small-a: cheap tokens, long reasoning, low cache hits, often needs a retry, passes about half.
    attempts = rng.choice([1, 2, 2, 3])
    ok = rng.random() < 0.45
    for a in range(1, attempts + 1):
        prompt, cached, out = j(32000), 0, j(12000)
        cached = int(prompt * rng.uniform(0.1, 0.3))
        rows.append({"model": "small-a", "task": t, "attempt": a,
                     "passed": (ok if a == attempts else False),
                     "usage": {"prompt_tokens": prompt, "completion_tokens": out,
                               "prompt_tokens_details": {"cached_tokens": cached},
                               "completion_tokens_details": {"reasoning_tokens": int(out * 0.8)}}})
    # mid-b: one attempt, good cache reuse, short output, passes most.
    inp = j(20000)
    cached = int(inp * rng.uniform(0.55, 0.7))
    write = j(1500)
    rows.append({"model": "mid-b", "task": t, "attempt": 1, "passed": rng.random() < 0.9,
                 "usage": {"input_tokens": inp - cached - write, "cache_read_input_tokens": cached,
                           "cache_creation_input_tokens": write, "output_tokens": j(1500)}})
    # large-c: one attempt, terse, passes every task here.
    inp = j(18000)
    cached = int(inp * rng.uniform(0.6, 0.75))
    out = j(1200)
    rows.append({"model": "large-c", "task": t, "attempt": 1, "passed": True,
                 "usage": {"input_tokens": inp, "input_tokens_details": {"cached_tokens": cached},
                           "output_tokens": out, "output_tokens_details": {"reasoning_tokens": int(out * 0.5)}}})

with open(os.path.join(HERE, "runs.jsonl"), "w") as f:
    f.write("// SAMPLE DATA: made-up models and token counts, generated by examples/make_sample.py\n")
    for r in rows:
        f.write(json.dumps(r) + "\n")
with open(os.path.join(HERE, "prices.json"), "w") as f:
    json.dump(PRICES, f, indent=2)
    f.write("\n")
print("wrote examples/runs.jsonl (%d calls) and examples/prices.json" % len(rows))
